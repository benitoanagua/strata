#!/usr/bin/env node
/**
 * Builds the distributable skin: syncs generated CSS, then assembles
 * dist/Strata/ — the directory name MUST match the skin name (`Strata`)
 * expected by MediaWiki's skin discovery.
 *
 * - skin.json is emitted with `version` injected from package.json so the
 *   skin metadata can never drift from the package version.
 * - resources/strata-fonts.js is generated from tokens.fontsUrl and
 *   registered as the `skins.strata.fonts` ResourceLoader module. It
 *   injects the Google Fonts <link> tags at runtime — skins cannot edit
 *   <head> directly and ResourceLoader CSS must stay local, so a small
 *   script module is the supported mechanism (see docs/MEDIAWIKI.md).
 * - composer.json uses the `mediawiki-skin` installer type with
 *   extra.installer-name so Composer installs into skins/Strata/.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const repoRoot = path.resolve(pkgRoot, "../..");
const distSkin = path.join(pkgRoot, "dist", "Strata");

execFileSync(process.execPath, [path.join(here, "sync-tokens.mjs")], {
  stdio: "inherit",
});

const pkg = JSON.parse(
  fs.readFileSync(path.join(pkgRoot, "package.json"), "utf8"),
);
const tokens = JSON.parse(
  fs.readFileSync(
    path.join(repoRoot, "packages/tokens/src/tokens.json"),
    "utf8",
  ),
);
const skinJson = JSON.parse(
  fs.readFileSync(path.join(pkgRoot, "skin.json"), "utf8"),
);
skinJson.version = pkg.version;

const fontsUrl = new URL(tokens.fontsUrl);
const fontsJs = `/* Generated by scripts/build.mjs from @strata/tokens fontsUrl.
 * Injects the Google Fonts <link> tags. ResourceLoader CSS must be local
 * and skins cannot edit <head>, so the font stylesheet is attached here.
 * Do not edit by hand — rebuild instead. */
( function () {
	'use strict';
	var preconnects = [ '${fontsUrl.origin}', 'https://fonts.gstatic.com' ];
	var stylesheet = '${tokens.fontsUrl}';
	preconnects.forEach( function ( href ) {
		var link = document.createElement( 'link' );
		link.rel = 'preconnect';
		link.href = href;
		if ( href === 'https://fonts.gstatic.com' ) {
			link.crossOrigin = '';
		}
		document.head.appendChild( link );
	} );
	var css = document.createElement( 'link' );
	css.rel = 'stylesheet';
	css.href = stylesheet;
	document.head.appendChild( css );
}() );
`;

const composer = {
  name: "benitoanagua/strata-skin",
  description: pkg.description,
  type: "mediawiki-skin",
  version: pkg.version,
  license: "MIT",
  require: {
    "composer/installers": "^1.0 || ^2.0",
  },
  extra: {
    "installer-name": "Strata",
  },
};

fs.rmSync(distSkin, { recursive: true, force: true });
for (const dir of ["i18n", "resources", "templates"]) {
  fs.cpSync(path.join(pkgRoot, dir), path.join(distSkin, dir), {
    recursive: true,
  });
}
fs.writeFileSync(
  path.join(distSkin, "skin.json"),
  JSON.stringify(skinJson, null, 2) + "\n",
);
fs.writeFileSync(
  path.join(distSkin, "composer.json"),
  JSON.stringify(composer, null, 2) + "\n",
);
fs.writeFileSync(path.join(distSkin, "resources/strata-fonts.js"), fontsJs);
console.log(`built dist/Strata (version ${pkg.version})`);
